#!/usr/bin/env python3
"""Regenerate everything in sample_output/ from the puzzles in puzzles/.

    python generate_samples.py

Writes, for each puzzle:
  sample_output/<puzzle>.txt                  full console output of `main.py --algo all --count-solutions`
  sample_output/images/<puzzle>.png           solved grid, coloured by vertex colour
  sample_output/images/<puzzle>_welsh_powell.png   Welsh-Powell result (grey = colour > n)
plus sample_output/images/mini_4x4_graph.png and sample_output/benchmark.md.
Times depend on the machine; node counts are deterministic.
"""

from __future__ import annotations

import contextlib
import io
import os
import platform
from pathlib import Path

import main
from sudoku_coloring import ALGORITHMS, SudokuGraph, count_solutions, find_conflicts, grid_to_colors, load_grid, welsh_powell

ROOT = Path(__file__).resolve().parent
PUZZLES = ROOT / "puzzles"
OUT = ROOT / "sample_output"
IMAGES = OUT / "images"
MAX_NODES = 1_000_000


def main_samples() -> None:
    os.chdir(ROOT)  # outputs use paths relative to the project root
    IMAGES.mkdir(parents=True, exist_ok=True)
    puzzles = sorted(PUZZLES.glob("*.txt"))

    for path in puzzles:
        name = path.stem
        buffer = io.StringIO()
        graph_png = str(IMAGES / f"{name}_graph.png") if name == "mini_4x4" else None
        with contextlib.redirect_stdout(buffer):
            print(f"$ python main.py puzzles/{path.name} --algo all --count-solutions\n")
            main.run(f"puzzles/{path.name}", "all", MAX_NODES, True,
                     png=str(IMAGES / f"{name}.png"), graph_png=graph_png)
        text = buffer.getvalue().replace(str(ROOT) + "/", "")
        (OUT / f"{name}.txt").write_text(text, encoding="utf-8")
        print(f"wrote sample_output/{name}.txt")

    rows = []
    for path in puzzles:
        grid = load_grid(path)
        n = len(grid)
        graph = SudokuGraph(n)
        clues = grid_to_colors(grid)
        if find_conflicts(graph, clues):
            rows.append(f"| `{path.name}` | {n}x{n} | {sum(1 for c in clues if c)} | invalid clues "
                        "| - | - | - | - |")
            continue
        sols = count_solutions(graph, n, clues, limit=10_000)
        cells = []
        for algo in ALGORITHMS.values():
            res = algo(graph, n, clues, max_nodes=MAX_NODES)
            if res.aborted:
                cells.append(f"aborted (> {MAX_NODES:,} nodes, {res.time_ms / 1000:.1f} s)")
            elif res.solved:
                cells.append(f"{res.nodes:,} nodes, {res.time_ms:.1f} ms")
            else:
                cells.append(f"no solution ({res.nodes} nodes)")
        wp = welsh_powell(graph, n, clues)
        wp_cell = f"{wp.colors_used} colours ({wp.extra['cells_over_k']} cells > {n})"
        sols_cell = "10000+" if sols >= 10_000 else str(sols)
        rows.append(f"| `{path.name}` | {n}x{n} | {sum(1 for c in clues if c)} | {sols_cell} | "
                    + " | ".join(cells) + f" | {wp_cell} |")

    header = (
        "# Benchmark\n\n"
        f"Generated by `python generate_samples.py` (Python {platform.python_version()}, "
        f"{platform.system()} {platform.machine()}). Node counts are deterministic, times depend on the machine.\n"
        f"Search budget for backtracking: {MAX_NODES:,} nodes.\n\n"
        "| Puzzle | Size | Clues | Solutions | Basic backtracking (lecture) | DSATUR/MRV + FC | "
        "DSATUR/MRV + FC, degree tie-break | Welsh-Powell |\n"
        "|---|---|---|---|---|---|---|---|\n"
    )
    (OUT / "benchmark.md").write_text(header + "\n".join(rows) + "\n", encoding="utf-8")
    print("wrote sample_output/benchmark.md")


if __name__ == "__main__":
    main_samples()
